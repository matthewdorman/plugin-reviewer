def rows(site, data):
    out = []
    for name, ver, status, typ, cat, upd, tested, inst, ab, sec, pf, rep, flags in data:
        comp = ab + sec + pf + rep
        out.append(
            dict(
                site=site,
                plugin=name,
                version=ver,
                status=status,
                type=typ,
                category=cat,
                wporg_last_updated=(
                    upd or "n/a (not on wp.org)" if typ in ("free",) else (upd or "n/a")
                ),
                wporg_tested=tested or "-",
                active_installs=inst if inst is not None else "-",
                abandonment=ab,
                security=sec,
                performance=pf,
                replaceability=rep,
                composite=comp,
                notes=flags,
            )
        )
    return out


