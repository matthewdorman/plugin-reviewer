def stats(site, data):
    act = [p for p in data if p[2] == "active"]
    ina = [p for p in data if p[2] == "inactive"]
    prem = [p for p in data if p[3] == "premium"]
    cust = [p for p in data if p[3] == "custom"]
    free = [p for p in data if p[3] == "free"]
    high = [p for p in data if (p[8] + p[9] + p[10] + p[11]) >= 13]
    return dict(
        site=site,
        total=len(data),
        active=len(act),
        inactive=len(ina),
        premium=len(prem),
        custom=len(cust),
        free=len(free),
        high_risk=len(high),
    )


